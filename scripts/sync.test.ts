import { describe, expect, test } from "bun:test";
import { buildGeminiInstructions } from "./sync.ts";

describe("sync.ts", () => {
  test("buildGeminiInstructions stays compact and independent of .claude", () => {
    const text = buildGeminiInstructions();
    expect(text).toContain("Generated by ~/.gemini/scripts/sync.ts");
    expect(text).not.toMatch(/\.claude\b/i);
    expect(Buffer.byteLength(text, "utf8")).toBeLessThan(24_000);
  });
});
