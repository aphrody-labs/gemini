// Builds upstream/INDEX.md (one line per skill, extension, MCP server and source) and upstream/catalog.json from the
// vendored files, so an agent finds what exists without opening the tree.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { OUT, loadPages, loadPointers, loadSources, slug } from "./upstream.ts";

export type Skill = { source: string; path: string; name: string; description: string };
export type Extension = { source: string; name: string; version?: string; description: string; mcp: string[]; commands: number; skills: number };

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) yield* walk(path);
    else yield path;
  }
}

/** The name and description of a SKILL.md, read as YAML and, when that fails, line by line. */
export function skillMeta(text: string): { name?: string; description?: string } {
  const block = text.match(/^---\n([\s\S]*?)\n---/)?.[1];
  if (!block) return {};
  try {
    const parsed = Bun.YAML.parse(block) as Record<string, unknown>;
    return { name: String(parsed.name ?? ""), description: String(parsed.description ?? "") };
  } catch {
    const pick = (key: string) => block.match(new RegExp(`^${key}:\\s*(.*)$`, "m"))?.[1]?.replace(/^["']|["']$/g, "");
    return { name: pick("name"), description: pick("description") };
  }
}

const oneLine = (text: string, max = 150) => text.replace(/\s+/g, " ").trim().slice(0, max);

export async function buildIndex() {
  const skills: Skill[] = [];
  const extensions: Extension[] = [];
  const mcp: Record<string, string[]> = {};
  const stats: { source: string; files: number; kb: number }[] = [];
  for (const source of loadSources()) {
    const dir = join(OUT, slug(source.repo));
    if (!existsSync(dir)) continue;
    let files = 0;
    let bytes = 0;
    for (const file of walk(dir)) {
      files++;
      bytes += statSync(file).size;
      const rel = relative(dir, file).replaceAll("\\", "/");
      if (/(^|\/)SKILL\.md$/.test(rel)) {
        const meta = skillMeta(readFileSync(file, "utf8"));
        skills.push({ source: source.repo, path: rel, name: meta.name || rel.split("/").at(-2) || rel, description: oneLine(meta.description ?? "") });
      } else if (/(^|\/)gemini-extension\.json$/.test(rel)) {
        try {
          const manifest = JSON.parse(readFileSync(file, "utf8")) as { name?: string; version?: string; description?: string; mcpServers?: Record<string, unknown> };
          const base = rel.replace(/gemini-extension\.json$/, "");
          const servers = Object.keys(manifest.mcpServers ?? {});
          const count = (pattern: RegExp) => [...walk(dir)].filter((f) => relative(dir, f).replaceAll("\\", "/").startsWith(base) && pattern.test(f.replaceAll("\\", "/"))).length;
          extensions.push({ source: source.repo, name: manifest.name ?? source.repo.split("/")[1]!, version: manifest.version, description: oneLine(manifest.description ?? ""), mcp: servers, commands: count(/\/commands\/.*\.toml$/), skills: count(/SKILL\.md$/) });
          if (servers.length) mcp[`${source.repo}${base ? `:${base}` : ""}`] = servers;
        } catch {}
      }
    }
    stats.push({ source: source.repo, files, kb: Math.round(bytes / 1024) });
  }
  skills.sort((a, b) => a.source.localeCompare(b.source) || a.path.localeCompare(b.path));
  extensions.sort((a, b) => a.name.localeCompare(b.name));

  const lines = ["# Upstream index", "", "Generated by `bun scripts/upstream.ts fetch`; do not edit. Pins are in `lock.json`, sources in `upstream.toml`.", ""];
  lines.push(`## Sources (${stats.length})`, "", "| Source | Kind | Files | KB |", "|---|---|---:|---:|");
  const kinds = new Map(loadSources().map((s) => [s.repo, s.kind]));
  for (const s of stats) lines.push(`| ${s.source} | ${kinds.get(s.source)} | ${s.files} | ${s.kb} |`);
  for (const p of loadPointers()) lines.push(`| ${p.repo} | pointer | 0 | 0 |`);
  lines.push("", `## Extensions (${extensions.length})`, "");
  for (const e of extensions) lines.push(`- **${e.name}** (${e.source}) ${e.description}${e.mcp.length ? ` MCP: ${e.mcp.join(", ")}.` : ""}${e.commands ? ` ${e.commands} commands.` : ""}${e.skills ? ` ${e.skills} skills.` : ""}`);
  lines.push("", `## Skills (${skills.length})`, "");
  for (const s of skills) lines.push(`- **${s.name}** (${s.source}/${s.path}) ${s.description}`);
  lines.push("", "## Pointers (not copied)", "");
  for (const p of loadPointers()) lines.push(`- ${p.repo}: ${p.note}`);
  const pages = loadPages();
  if (pages.length) lines.push("", "## Pages", "", ...pages.map((p) => `- ${p.path}: ${p.url} (${p.license})`));
  writeFileSync(join(OUT, "INDEX.md"), lines.join("\n") + "\n");
  writeFileSync(join(OUT, "catalog.json"), JSON.stringify({ sources: stats, extensions, skills, mcp }, null, 2) + "\n");
  console.log(`index: ${stats.length} sources, ${extensions.length} extensions, ${skills.length} skills, ${Object.keys(mcp).length} MCP manifests`);
}

if (import.meta.main) await buildIndex();
